#!/usr/bin/env python3
"""Convert source PNG/JPG machine photos to web-ready WebP + write a PHP manifest.
Usage: python3 tools/optimize_images.py <source_dir> [out_dir]
Needs: pip install pillow"""
import re, sys, json
from pathlib import Path
from PIL import Image

src = Path(sys.argv[1])
out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "public/assets/img/machines"
SIZES = {"1600": 1600, "640": 640}

def slug(s):
    s = re.sub(r"\.[^.]+$", "", s).lower()
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return s or "image"

manifest = {}
for d in sorted(p for p in src.iterdir() if p.is_dir()):
    cat = slug(d.name)
    seen = set()
    for f in sorted(d.iterdir()):
        if f.suffix.lower() not in (".png", ".jpg", ".jpeg"): continue
        name = slug(f.name); n = name; i = 2
        while n in seen: n = f"{name}-{i}"; i += 1
        seen.add(n)
        im = Image.open(f).convert("RGB")
        entry = {"title": f.stem.replace("_", " ").strip(" -"), "files": {}}
        (out / cat).mkdir(parents=True, exist_ok=True)
        for tag, maxw in SIZES.items():
            w, h = im.size
            if w > maxw: h = round(h * maxw / w); w = maxw
            r = im.resize((w, h), Image.LANCZOS) if (w, h) != im.size else im
            r.save(out / cat / f"{n}-{tag}.webp", "WEBP", quality=78, method=6)
            entry["files"][tag] = [w, h]
        manifest[f"{cat}/{n}"] = entry

def php(v, ind=0):
    pad = "    " * ind
    if isinstance(v, dict):
        return "[\n" + "".join(f"{pad}    {json.dumps(k)} => {php(x, ind+1)},\n" for k, x in v.items()) + pad + "]"
    if isinstance(v, list): return "[" + ", ".join(php(x) for x in v) + "]"
    return json.dumps(v)

(Path(__file__).resolve().parent.parent / "app/Data/ImageManifest.php").write_text(
    "<?php\n// GENERATED by tools/optimize_images.py - do not edit.\nreturn " + php(manifest) + ";\n")
print(len(manifest), "images processed")
